import { existsSync, readdirSync, readFileSync, realpathSync } from "node:fs";
import path from "node:path";
import { CACHE_DIR, CONTEXT_DIR, type RepoConfig, type TargetTool } from "./config.ts";
import { warning, type Diagnostic } from "./diagnostics.ts";
import type { FactReport } from "./facts.ts";
import type { ResolvedRule, RuleSet } from "./compose.ts";
